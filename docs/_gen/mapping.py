"""Write docs/mapping.md: TorchVIC function -> VIC 5.1.0 C file:line citations.

Run from the repository root:  python docs/_gen/mapping.py > docs/mapping.md
A row is every top-level function or method of torchvic/ whose docstring or
comments cite a C source (name.c:LINE or name.c:LINE-LINE).
"""
import ast
import os
import re

CITE = re.compile(r'\b([A-Za-z_][A-Za-z_0-9]*\.c):(\d+(?:-\d+)?)')
ROOT = 'torchvic'


def rows(path):
    src = open(path, encoding='utf-8').read()
    lines = src.splitlines()
    tree = ast.parse(src)
    out = []

    def visit(node, prefix):
        for ch in ast.iter_child_nodes(node):
            if isinstance(ch, ast.ClassDef):
                visit(ch, prefix + ch.name + '.')
            elif isinstance(ch, (ast.FunctionDef, ast.AsyncFunctionDef)):
                text = '\n'.join(lines[ch.lineno - 1:ch.end_lineno])
                seen = []
                for f, n in CITE.findall(text):
                    c = '%s:%s' % (f, n)
                    if c not in seen:
                        seen.append(c)
                if seen:
                    out.append((prefix + ch.name, ch.lineno, seen))
    visit(tree, '')
    return out


def main():
    print('# Process-to-C mapping\n')
    print('Each row is a TorchVIC function and the VIC 5.1.0 C sources its '
          'docstring or comments cite (file:line as in the VIC tree under '
          '`reference/VIC-5.1.0`). The page is generated by '
          '`docs/_gen/mapping.py` from those citations; citations are listed '
          'in the order they appear, up to eight per function.\n')
    for d, _, fs in sorted(os.walk(ROOT)):
        for f in sorted(fs):
            if not f.endswith('.py'):
                continue
            p = os.path.join(d, f)
            rs = rows(p)
            if not rs:
                continue
            print('## `%s`\n' % p.replace(os.sep, '/'))
            print('| function | line | VIC 5.1.0 C source |')
            print('|---|---|---|')
            for name, ln, cs in rs:
                more = ' ...' if len(cs) > 8 else ''
                print('| `%s` | %d | %s%s |' % (name, ln,
                      ', '.join('`%s`' % c for c in cs[:8]), more))
            print()


if __name__ == '__main__':
    main()
