#!/usr/bin/env python3
"""docs/OUTPUT_VARIABLES.md from torchvic.io.history and the VIC inventory.

    python tools/gen_output_variables.py > docs/OUTPUT_VARIABLES.md
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from torchvic.io import history as H                        # noqa: E402

#: variables whose rows exist only on a full-energy run
EB_ONLY = {'OUT_ADV_SENS', 'OUT_SOIL_TNODE', 'OUT_AERO_COND1', 'OUT_AERO_COND2',
           'OUT_AERO_RESIST1', 'OUT_AERO_RESIST2', 'OUT_SOIL_TNODE_WL'}
ZERO_WITHOUT = {
    'OUT_SUB_BLOWING': 'BLOWING FALSE', 'OUT_SURFSTOR': 'LAKES FALSE',
    'OUT_DELSURFSTOR': 'LAKES FALSE', 'OUT_SOIL_TNODE_WL': 'LAKES FALSE',
    'OUT_ADV_SENS': 'SPATIAL_SNOW FALSE', 'OUT_DISCHARGE': 'no RVIC extension',
    'OUT_SURF_COND': 'put_data.c never sets it',
    'OUT_IN_LONG_BAND': 'put_data.c never sets it',
    'OUT_GPP': 'CARBON FALSE', 'OUT_NPP': 'CARBON FALSE',
    'OUT_RAUT': 'CARBON FALSE', 'OUT_RHET': 'CARBON FALSE',
    'OUT_NEE': 'CARBON FALSE', 'OUT_APAR': 'CARBON FALSE',
    'OUT_LITTERFALL': 'CARBON FALSE', 'OUT_CLITTER': 'CARBON FALSE',
    'OUT_CINTER': 'CARBON FALSE', 'OUT_CSLOW': 'CARBON FALSE'}
MISSING_WITHOUT = {'OUT_CATM': 'CARBON FALSE', 'OUT_FDIR': 'CARBON FALSE',
                   'OUT_PAR': 'CARBON FALSE',
                   'OUT_ENERGY_ERROR': 'FULL_ENERGY FALSE'}
NOT_REPRODUCIBLE = {
    'OUT_TIME_VICRUN_WALL': 'a wall-clock timer of the VIC run',
    'OUT_TIME_VICRUN_CPU': 'a CPU-time timer of the VIC run'}
NOTES = {
    'OUT_ENERGY_ERROR': 'default: the surface solver\'s residual; '
                        '`--energy-error vic` / `energy_error=\'vic\'`: '
                        'put_data.c:538-552 from the reported rows',
    'OUT_SUB_SURFACE': 'minus OUT_SUB_SNOW without BLOWING (snow_melt.c:479 '
                       'flips only vapor_flux)',
    'OUT_SOIL_TNODE': 'QUICK_FLUX: the three nodes; NODES otherwise',
    'OUT_FDEPTH': 'find_0_degree_fronts on the step\'s nodes, cm, FROZEN_SOIL',
    'OUT_TDEPTH': 'as OUT_FDEPTH',
    'OUT_SURFT_FBFLAG': 'zero when the run took no temperature fallback; '
                        'left out of a run that did',
}


def main():
    meta = H.outvar_metadata()
    print('# Output variables\n')
    print('Generated by `tools/gen_output_variables.py` from '
          '`torchvic.io.history` and VIC 5.1.0\'s own table '
          '(`torchvic/data/vic5_outvars.json`). VIC 5.1.0 defines %d OUT_* '
          'variables (5.0.1: the same without OUT_DISCHARGE).\n' % len(meta))
    print('Every variable is aggregated and written as `OUTFILE`/`OUTVAR` '
          'asks (see the history writer); `Source` is the `basin.simulate` '
          'row it comes from. "exact" means within 1e-12 (absolute, or '
          'relative above 1) of the pristine `vic_image.exe` on the '
          'verification matrix rows (`tests/test_out_vars.py`).\n')
    print('| variable | units | dim | agg | status | source / note |')
    print('|---|---|---|---|---|---|')
    for n in sorted(meta):
        m = meta[n]
        src = H.OUTVAR_SOURCES.get(n)
        if isinstance(src, tuple):
            src = ' '.join(src)
        if n in NOT_REPRODUCIBLE:
            st, note = 'not reproducible', NOT_REPRODUCIBLE[n]
        elif src is None:
            st, note = 'not computed', 'no TorchVIC row (see below)'
        elif n in ZERO_WITHOUT:
            st, note = 'exact', '`%s`; zero with %s' % (src, ZERO_WITHOUT[n])
        elif n in MISSING_WITHOUT:
            st, note = 'exact', '`%s`; MISSING (-99999) with %s' % (
                src, MISSING_WITHOUT[n])
        else:
            st, note = 'exact', '`%s`' % src
        if n in NOTES:
            note += '; ' + NOTES[n]
        print('| %s | %s | %s | %s | %s | %s |' % (
            n, m.get('units', ''), m.get('dim') or '', H.default_agg(n),
            st, note))
    print('\n## Reading the table\n')
    print(open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            'output_variables_notes.md')).read())


if __name__ == '__main__':
    main()
